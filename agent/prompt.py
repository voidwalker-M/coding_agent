REFLECTION_TEST_FAILED = """\
[REFLECTION] The tests just failed. Before your next action, consider:
1. Read the full error message above carefully — what is the root cause?
2. Is your last edit correct? Did it introduce a new bug?
3. Do you need to look at more context before editing again?

Be specific about what you will do differently. What is your next action?\
"""

REFLECTION_NO_EDIT = """\
[REFLECTION] You have taken {n} steps without editing any file.
You may be stuck in an exploration loop. Consider:
1. Do you have enough context to make a change now?
2. If yes — make the edit
3. If no — identify exactly what you still need, get it in one targeted step, then edit

What specific action will move the task forward?\
"""

REFLECTION_LOOP_DETECTED = """\
[REFLECTION] You have repeated the same action {n} times in a row.
This suggests you are stuck. Stop and reconsider:
1. What are you trying to achieve with this action?
2. Why isn't it working?
3. What completely different approach could you try?

Do not repeat the same action again.\
"""


def reflection_test_failed() -> str:
    return REFLECTION_TEST_FAILED


def reflection_no_edit(n: int) -> str:
    return REFLECTION_NO_EDIT.format(n=n)


def reflection_loop_detected(n: int) -> str:
    return REFLECTION_LOOP_DETECTED.format(n=n)


NOOP_FINISH_CORRECTION = """\
You called finish, but the working tree has NO changes — you have \
not edited any file yet. Describing the fix is not enough; you must \
APPLY it. Use the file_edit tool to make the change to the target \
file (or file_write to rewrite it), then verify with git diff. Do \
not finish until your change is actually on disk.\
"""


def noop_finish_correction() -> str:
    return NOOP_FINISH_CORRECTION


UNVERIFIED_FINISH_CORRECTION = """\
You called finish after editing the repo, but you have not successfully \
run tests since that edit. A passing test is the only evidence the fix works.

Call the test tool on the tests named in the issue / error output (or the \
closest matching file). If they fail, read the assertion, search_text for \
that symbol, and edit THAT definition — do not edit unrelated files. \
Only finish after tests you can run are green.\
"""


def unverified_finish_correction() -> str:
    return UNVERIFIED_FINISH_CORRECTION


LOCATE_BEFORE_EDIT_CORRECTION = """\
You tried to edit before locating the failing code. Search first.

Call search_text or find_symbol with a concrete name from the issue / traceback \
(function, class, or error string). Only after that hits, file_edit the matching \
*library* definition — not a test file and not a nearby file that merely looks related.\
"""


def locate_before_edit_correction() -> str:
    return LOCATE_BEFORE_EDIT_CORRECTION


# ---------------------------------------------------------------------------
# Task prompt (user message describing the task)
# ---------------------------------------------------------------------------

_TASK_TEMPLATE = """\
Please fix the following issue in the repository at {repo_path}.

## Task
{description}
{issue_section}
## Instructions
- Start by exploring the repository to understand the codebase
- Make the minimal changes necessary to fix the issue
- Search for the exact failing test / symbol from the issue before editing
- Change library code only — do not rewrite files under tests/
- Run the tests to verify your fix works; if they fail, fix the cause and re-run
- When complete, call finish with a summary of your changes. Do not finish with \
an empty diff, and do not finish without running tests after the last edit\
"""

_ISSUE_SECTION_TEMPLATE = """
## GitHub Issue
URL: {issue_url}
"""


def build_task_prompt(
    description: str,
    repo_path: str,
    issue_url: str | None = None,
) -> str:
    """
    Build the user message that describes the task (the first user message in the conversation).

    Args:
        description: task description in natural language
        repo_path:   path to the repo root
        issue_url:   GitHub issue URL (optional)
    """
    issue_section = ""
    if issue_url:
        issue_section = _ISSUE_SECTION_TEMPLATE.format(issue_url=issue_url)

    return _TASK_TEMPLATE.format(
        repo_path=repo_path,
        description=description.strip(),
        issue_section=issue_section,
    )
