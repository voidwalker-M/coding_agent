"""
agent/prompt.py

System prompt template management.

Responsibilities:
- Maintain the agent's system prompt templates
- Render the final prompt from runtime information (tool list, repo summary)
- Provide Reflection prompt templates

Design principles:
- All prompts are centralized here; editing prompts never requires touching core.py
- Templates use str.format() instead of jinja2 to minimize dependencies
- Each prompt has a corresponding function for easy testing and tuning
"""

from __future__ import annotations

from llm.base import LLMToolSchema


# ---------------------------------------------------------------------------
# System prompt
# ---------------------------------------------------------------------------

_SYSTEM_TEMPLATE = """\
You are an autonomous coding agent. Your goal is to understand a coding task, \
explore the repository, make the necessary code changes, and verify they work correctly.

## Workflow
1. **Explore**: Understand the repository structure and the problem
2. **Plan**: Identify what needs to change; use the plan tool for a numbered checklist
3. **Edit**: Make precise, minimal changes using the available tools
4. **Verify**: Run tests to confirm the fix works
5. **Finish**: Call finish with a clear summary of what you changed

## Rules
- Think step by step before each action (use the thought field)
- Locate the failing symbol (search_text / find_symbol on names from the issue \
or traceback) BEFORE editing. Do not patch a nearby file because the name looks related
- Do NOT edit or rewrite files under tests/ or test_*.py — fix the library \
implementation. Evaluation applies its own tests after you finish
- After editing files, always run tests to verify your changes
- If tests fail, read the error carefully and fix the root cause, not the symptom
- Do not edit unrelated files; a passing new test that breaks old tests is a failed fix
- If you are stuck after several attempts, reflect on your approach and try differently
- Make the smallest change that fixes the problem
- Do not call finish until a real edit is on disk AND tests you can run have passed
- When done, call finish. If you truly cannot solve it, call give_up with an explanation

## Efficiency (minimize wasted tokens)
- Do NOT re-read a file you have already read **unless you edited it (file_write /
  file_edit / undo) or a test/compiler error points at it** — then file_read from
  disk; the copy in this conversation is stale
- Prefer targeted tools (find_symbol, search_text, file_view of a line range) over reading
  whole files or running broad `cat`/`grep` that dump large output
- Keep the thought field concise: a sentence or two of reasoning, not an essay
- Use the repository summary above to locate code before opening files
- One purposeful action per step; avoid speculative exploration once you can edit

## Repository
Path: {repo_path}
{repo_summary}
{rules_section}{retrieved_section}{memory_section}{working_memory_section}{plan_section}
## Available tools
{tool_descriptions}
"""

_NO_REPO_SUMMARY = "(Repository summary not yet available — use find_files and file_read to explore)"


def build_system_prompt(
    repo_path: str,
    tools: list[LLMToolSchema],
    repo_summary: str | None = None,
    retrieved_context: str | None = None,
    memory_context: str | None = None,
    working_memory: str | None = None,
    rules_context: str | None = None,
    plan_context: str | None = None,
) -> str:
    """
    Render the complete system prompt.

    Args:
        repo_path:         path to the repo root
        tools:             list of registered tool schemas
        repo_summary:      static structural summary generated by the repo-map
        retrieved_context: RAG-retrieved code chunks relevant to the task (optional)
        memory_context:    recalled approved memories for this task (optional)
        working_memory:    short-term conversation window (prior queries, files)
        rules_context:     project rules from AGENTS.md / CLAUDE.md / .cursor/rules
        plan_context:      remaining structured plan steps (optional)

    Returns:
        The rendered system prompt string
    """
    tool_descriptions = _format_tool_descriptions(tools)
    summary = repo_summary or _NO_REPO_SUMMARY
    rules_section = f"\n{rules_context}\n" if rules_context else ""
    retrieved_section = f"\n{retrieved_context}\n" if retrieved_context else ""
    memory_section = f"\n{memory_context}\n" if memory_context else ""
    working_memory_section = f"\n{working_memory}\n" if working_memory else ""
    plan_section = f"\n{plan_context}\n" if plan_context else ""

    return _SYSTEM_TEMPLATE.format(
        repo_path=repo_path,
        repo_summary=summary,
        rules_section=rules_section,
        retrieved_section=retrieved_section,
        memory_section=memory_section,
        working_memory_section=working_memory_section,
        plan_section=plan_section,
        tool_descriptions=tool_descriptions,
    )


def _format_tool_descriptions(tools: list[LLMToolSchema]) -> str:
    """Format the tool list as a readable description block."""
    if not tools:
        return "(no tools available)"
    lines = []
    for tool in tools:
        lines.append(f"- **{tool.name}**: {tool.description}")
    return "\n".join(lines)


